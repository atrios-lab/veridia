/** A code of the list, or null when it is not one of them. */
export function codeIn(
  list: ReadonlyMap<number, string>,
  value: unknown,
): number | null {
  const n =
    typeof value === "number" ? value : Number(String(value ?? "").trim());
  return Number.isInteger(n) && list.has(n) ? n : null;
}

const fold = (text: string) =>
  text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

/**
 * The street kind a written address starts with ("Rua", "Av.", "Sítio",
 * "Rodovia RN-064"), or null. Abbreviations the offices write most.
 */
export function streetKindOf(address: string): number | null {
  const text = fold(address);
  if (!text) return null;
  const abbreviations: Record<string, number> = {
    av: 26,
    "av.": 26,
    r: 250,
    "r.": 250,
    rod: 247,
    "rod.": 247,
    trav: 273,
    "trav.": 273,
    tv: 273,
    "tv.": 273,
    estr: 117,
    "estr.": 117,
    faz: 121,
    "faz.": 121,
    pc: 215,
    pca: 215,
    "pc.": 215,
    povoado: 214,
    sitio: 263,
    "sit.": 263,
    al: 10,
    "al.": 10,
  };
  const first = text.split(/\s+/)[0];
  if (first && abbreviations[first]) return abbreviations[first];
  let best: { code: number; size: number } | null = null;
  for (const [code, name] of STREET_KINDS) {
    const n = fold(name);
    if (
      (text === n || text.startsWith(`${n} `)) &&
      (!best || n.length > best.size)
    ) {
      best = { code, size: n.length };
    }
  }
  return best?.code ?? null;
}
